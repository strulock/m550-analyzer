#!/usr/bin/env python3
"""
channel_docs.py - generate the channel lookup in docs/channels/ from the catalogs.

  python tools/channel_docs.py           rewrite docs/channels/
  python tools/channel_docs.py --check   exit 1 if docs/channels/ is out of date

One Markdown file per module (DME and each module catalog), sections by
function group, one row per channel: name, identifier, field, type, unit,
scaling, value table, English and German description. docs/channels/README.md
indexes them. Generated, so never edit those files by hand: change the
catalogs (tools/module_catalog.py, tools/translate.py) and rerun this.
"""

import argparse
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(ROOT, "src"))

from n63read import core  # noqa: E402

OUT = os.path.join(ROOT, "docs", "channels")
ENUM_INLINE = 8                 # value tables up to this size are written out
PAGE_LIMIT = 400_000            # bytes; GitHub stops rendering large Markdown

# Module address -> (file stem, title, SGBD file).
DME_PAGE = ("DME", "Engine, master DME (0x12)", "dme8ff_r.prg")


def module_pages():
    pages = {}
    for name in core.MODULE_CATALOGS:
        path = core.resource_path(name + "_measurements.csv")
        if not os.path.exists(path):
            continue
        cat = {}
        import csv
        with open(path, encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                cat[row["ARG"]] = row
        if not cat:
            continue
        module = int(next(iter(cat.values()))["MODULE"], 16)
        label = core.KNOWN_MODULES.get(module) or core.MODULE_LABELS.get(module, "")
        pages[name] = ("%s (0x%02X)" % (label, module), name.lower() + ".prg", cat)
    return pages


def channel_group(name, meta, record_groups):
    """Same grouping as the GUI picker: records by job name first."""
    if not meta.get("MODULE"):
        return core.function_group(name, meta.get("INFO"), meta.get("INFO_EN"))
    key = (meta["MODULE"], meta["ID"])
    if key not in record_groups:
        job = name.split(".")[0]
        group = core.function_group(job)
        if group == core.OTHER_GROUP:
            group = core.function_group(job, meta.get("INFO"), meta.get("INFO_EN"))
        record_groups[key] = group
    return record_groups[key]


def cell(text):
    text = (text or "").strip()
    if text in ("-", ""):
        return ""
    return text.replace("|", "\\|").replace("\n", " ")


def scaling(meta):
    """'x × 0.1 − 48' style, leaving out identities."""
    def num(key, default):
        try:
            return float((meta.get(key) or "").strip())
        except ValueError:
            return default
    mul, div, add = num("MUL", 1.0), num("DIV", 1.0), num("ADD", 0.0)
    parts = []
    if mul != 1.0:
        parts.append("× %g" % mul)
    if div not in (0.0, 1.0):
        parts.append("÷ %g" % div)
    if add:
        parts.append("%s %g" % ("+" if add > 0 else "−", abs(add)))
    return " ".join(parts)


def _value_key(k):
    return (0, k, "") if isinstance(k, int) else (1, 0, str(k))


def values(meta, enums, vpage):
    """Short value tables inline; long ones linked to the module's values page."""
    table = (meta.get("NAME") or "").strip()
    if table in ("", "-"):
        return ""
    entries = enums.get(table.upper())
    if not entries:
        return "`%s`" % table
    if len(entries) > ENUM_INLINE:
        return "[`%s`](%s#%s) (%d values)" % (table, vpage, anchor(table), len(entries))
    return "; ".join("%s = %s" % (k, cell(v.get("text_en") or v.get("text_de")))
                     for k, v in sorted(entries.items(), key=lambda kv: _value_key(kv[0])))


def values_page(title, cat, enums):
    """Every value table a module's channels name, written out."""
    used = sorted({(m.get("NAME") or "").strip().upper() for m in cat.values()} - {"", "-"})
    out = [GENERATED_TITLE % ("%s: value tables" % title),
           "What the numbers of enumerated channels mean. The app logs and charts "
           "the number and shows the text in the Status column.\n"]
    for table in used:
        entries = enums.get(table)
        if not entries:
            continue
        out.append("\n## %s\n\n| Value | Meaning | German |\n|---|---|---|\n" % table)
        for k, v in sorted(entries.items(), key=lambda kv: _value_key(kv[0])):
            out.append("| %s | %s | %s |\n" % (k, cell(v.get("text_en")), cell(v.get("text_de"))))
    return "".join(out)


def field(meta):
    if not meta.get("MODULE"):
        return ""
    pos = (meta.get("POS") or "").strip()
    return "%s @%s" % (meta["FIELD"], pos) if pos else meta.get("FIELD", "")


GENERATED_TITLE = ("# %s\n\n<!-- Generated by tools/channel_docs.py from the catalogs. "
                   "Do not edit. -->\n\n")
TABLE_HEAD = ("| Channel | ID | Field | Type | Unit | Scaling | Values | Description | German |\n"
              "|---|---|---|---|---|---|---|---|---|\n")


def rows(names, cat, enums, vpage):
    out = []
    for name in sorted(names, key=lambda n: (cat[n]["ID"], int(cat[n].get("FIELD") or 0), n)):
        m = cat[name]
        out.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |\n" % (
            name, m["ID"], field(m), cell(m.get("DATENTYP")), cell(m.get("EINHEIT")),
            scaling(m), values(m, enums, vpage), cell(m.get("INFO_EN")), cell(m.get("INFO"))))
    return out


def intro(title, prg, n, vpage):
    return (GENERATED_TITLE % title
            + "%d channels from `%s`. Function groups are keyword-based (see "
              "[decoding](../decoding.md#function-groups)). Value tables: [%s](%s).\n\n"
              "Columns: **ID** is the identifier read with service 0x22; **Field** is the "
              "value's place in a multi-value reply (`@n` = fixed byte offset); "
              "**Scaling** applies to the raw number; **Values** is the value table "
              "(written out when short).\n\n" % (n, prg, vpage, vpage))


def pages(stem, title, prg, cat, enums):
    """{file name: content} for one module: one page, or an index plus a page
    per function group (in parts if need be) when one page would be too big."""
    record_groups, groups = {}, {}
    for name, meta in cat.items():
        groups.setdefault(channel_group(name, meta, record_groups), []).append(name)
    order = [g for g, _ in core.FUNCTION_GROUPS] + [core.OTHER_GROUP]
    present = [g for g in order if g in groups]
    vpage = stem + "-values.md"
    files = {vpage: values_page(title, cat, enums)}
    body = {g: rows(groups[g], cat, enums, vpage) for g in present}

    single = intro(title, prg, len(cat), vpage)
    single += "Groups: " + " · ".join("[%s](#%s) (%d)" % (g, anchor(g), len(groups[g]))
                                      for g in present) + "\n"
    for g in present:
        single += "\n## %s\n\n" % g + TABLE_HEAD + "".join(body[g])
    if len(single.encode("utf-8")) <= PAGE_LIMIT:
        files[stem + ".md"] = single
        return files

    index = intro(title, prg, len(cat), vpage) + "Too many for one page; one page per group:\n\n"
    for g in present:
        parts, part, size = [], [], 0
        for line in body[g]:
            n = len(line.encode("utf-8"))
            if part and size + n > PAGE_LIMIT - 2000:
                parts.append(part)
                part, size = [], 0
            part.append(line)
            size += n
        parts.append(part)
        links = []
        for i, part in enumerate(parts, 1):
            suffix = "" if len(parts) == 1 else "-%d" % i
            fname = "%s-%s%s.md" % (stem, anchor(g), suffix)
            heading = g if len(parts) == 1 else "%s (part %d of %d)" % (g, i, len(parts))
            files[fname] = (GENERATED_TITLE % ("%s: %s" % (title, heading))
                            + "[All groups](%s.md)\n\n" % stem + TABLE_HEAD + "".join(part))
            links.append("[%s](%s)" % ("part %d" % i if len(parts) > 1 else "page", fname))
        index += "- **%s** (%d): %s\n" % (g, len(groups[g]), ", ".join(links))
    files[stem + ".md"] = index
    return files


def anchor(heading):
    """GitHub's heading anchor."""
    a = heading.lower().replace(" ", "-")
    return "".join(c for c in a if c.isalnum() or c in "-_")


def build():
    """{file name: content} for docs/channels/."""
    enums = core.load_enum_tables()
    files = {}
    dme = core.load_catalog()
    index = [("DME.md", DME_PAGE[1], DME_PAGE[2], len(dme))]
    files.update(pages("DME", DME_PAGE[1], DME_PAGE[2], dme, enums))
    for name, (title, prg, cat) in sorted(module_pages().items(),
                                          key=lambda kv: kv[1][0]):
        files.update(pages(name, title, prg, cat, enums))
        index.append((name + ".md", title, prg, len(cat)))
    total = sum(n for *_, n in index)
    out = io.StringIO()
    w = out.write
    w("# Channel lookup\n\n")
    w("<!-- Generated by tools/channel_docs.py from the catalogs. Do not edit. -->\n\n")
    w("Every channel the app can read: %d across %d modules. One page per "
      "module, sectioned by function group. To find a channel by meaning, search "
      "these pages or use the GUI picker's filter; to find it by code name, "
      "search for the name.\n\n" % (total, len(index)))
    w("| Module | Source SGBD | Channels | Value tables |\n|---|---|---|---|\n")
    for fname, title, prg, n in index:
        w("| [%s](%s) | `%s` | %d | [values](%s) |\n"
          % (title, fname, prg, n, fname.replace(".md", "-values.md")))
    w("\nRegenerate with `python tools/channel_docs.py` after changing a catalog.\n")
    files["README.md"] = out.getvalue()
    return files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if out of date")
    args = ap.parse_args(argv)
    files = build()
    stale = []
    for fname, text in files.items():
        path = os.path.join(OUT, fname)
        try:
            # Universal newlines: a Windows checkout (core.autocrlf) turns
            # these into CRLF, which is not a change.
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            stale.append(fname)
            if not args.check:
                os.makedirs(OUT, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(text)
    extra = [f for f in (os.listdir(OUT) if os.path.isdir(OUT) else [])
             if f.endswith(".md") and f not in files]
    if args.check:
        if stale or extra:
            print("docs/channels out of date: %s - run python tools/channel_docs.py"
                  % ", ".join(stale + extra))
            return 1
        return 0
    for f in extra:
        os.remove(os.path.join(OUT, f))
    print("wrote %d file(s), removed %d" % (len(stale), len(extra)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
